"""
assets/g1/build_harness_model.py

Builds the harness's canonical robot model, `g1_29dof_harness.xml`, from
Unitree's upstream `g1_29dof_rev_1_0.xml` (copied unmodified from
unitreerobotics/unitree_rl_gym, resources/robots/g1_description).

We never hand-edit the robot. Every change the harness makes is listed here,
so anyone can see exactly how the evaluated robot differs from upstream:

  1. Joint defaults  damping=0.001  armature=0.01  frictionloss=0.1
     Upstream 29-DOF file has none. These are the values in unitree_rl_gym's
     g1_12dof.xml, the model used by Unitree's own MuJoCo sim2sim
     (deploy/deploy_mujoco). Without armature, light distal links (wrists)
     are numerically stiff under PD control.
  2. Nothing else. Masses, inertias, joint axes, ranges, torque limits
     (actuatorfrcrange) and collision geoms are Unitree's.

Run:  python assets/g1/build_harness_model.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
UPSTREAM = os.path.join(HERE, "g1_29dof_rev_1_0.xml")
OUTPUT = os.path.join(HERE, "g1_29dof_harness.xml")

JOINT_DEFAULTS = '  <default>\n    <joint damping="0.001" armature="0.01" frictionloss="0.1"/>\n  </default>\n'


def build() -> str:
    with open(UPSTREAM, "r", encoding="utf-8") as f:
        xml = f.read()
    if "<default>" in xml:
        raise RuntimeError("Upstream model already has a <default> block; review build script.")
    anchor = '<compiler angle="radian" meshdir="meshes"/>'
    if anchor not in xml:
        raise RuntimeError("Unexpected upstream file layout; compiler tag not found.")
    xml = xml.replace(anchor, anchor + "\n\n" + JOINT_DEFAULTS, 1)
    xml = xml.replace('<mujoco model="g1_29dof_rev_1_0">', '<mujoco model="g1_29dof_harness">', 1)
    header = ("<!-- GENERATED by build_harness_model.py from g1_29dof_rev_1_0.xml "
              "(unitree_rl_gym, BSD-3). Do not edit by hand. -->\n")
    return header + xml


if __name__ == "__main__":
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(build())
    print(f"Wrote {OUTPUT}")
